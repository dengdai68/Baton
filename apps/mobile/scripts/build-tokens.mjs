#!/usr/bin/env node
// Generate src/theme/tokens.generated.ts from the single Graphite source web/tokens.css.
// Colors keep their light/dark pairs; sizes follow a phone density documented below.
// Run: npm run tokens   (check mode: node scripts/build-tokens.mjs --check)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../../../web/tokens.css', import.meta.url));
const target = fileURLToPath(new URL('../src/theme/tokens.generated.ts', import.meta.url));
const css = readFileSync(source, 'utf8');
const block = css.match(/html:root, html:root\[data-theme\] \{([\s\S]*?)\n\}/)?.[1];
if (!block) throw new Error('tokens.css: root token block not found');

const raw = new Map();
for (const match of block.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)) raw.set(match[1], match[2].trim());

/** Split top-level commas (ignores commas inside nested parentheses). */
function splitArgs(text) {
  const parts = []; let depth = 0, start = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === '(') depth++;
    else if (text[i] === ')') depth--;
    else if (text[i] === ',' && depth === 0) { parts.push(text.slice(start, i).trim()); start = i + 1; }
  }
  parts.push(text.slice(start).trim());
  return parts;
}
/** Resolve a token to { light, dark } literal values, following var() references. */
function resolve(name, seen = new Set()) {
  if (seen.has(name)) throw new Error('token cycle at --' + name);
  seen.add(name);
  const value = raw.get(name);
  if (value === undefined) throw new Error('unknown token --' + name);
  const reference = value.match(/^var\(--([a-z0-9-]+)\)$/);
  if (reference) return resolve(reference[1], seen);
  const pair = value.match(/^light-dark\(([\s\S]+)\)$/);
  if (pair) { const [light, dark] = splitArgs(pair[1]); return { light, dark }; }
  return { light: value, dark: value };
}
const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const colorPrefixes = ['bg-', 'border', 'text', 'accent', 'focus', 'st-', 'live', 'code-', 'av-', 'syn-', 'on-solid', 'dark'];
const colorNames = [...raw.keys()].filter((name) => colorPrefixes.some((prefix) => name === prefix || name.startsWith(prefix)) && !name.startsWith('text-on-accent') || name === 'text-on-accent');
const light = {}, dark = {};
for (const name of colorNames) {
  const { light: l, dark: d } = resolve(name);
  if (!/^(#|rgba?\()/.test(l) || !/^(#|rgba?\()/.test(d)) continue;
  light[camel(name)] = l; dark[camel(name)] = d;
}
const px = (name) => Number(resolve(name).light.replace(/px$/, ''));
// Phone density: the desktop Graphite scale (13px body in 28px controls) is read
// at arm's length on a phone. Every step moves up together so hierarchy stays
// identical; touch controls meet the 44pt minimum.
const typeScale = {
  caption: { size: 12, line: 16 }, small: { size: 13, line: 18 }, body: { size: 15, line: 21 },
  read: { size: 16, line: 24 }, titleSm: { size: 17, line: 24 }, title: { size: 22, line: 28 }, display: { size: 28, line: 34 },
};
const metrics = {
  radius: { xs: px('r-xs'), sm: px('r-sm'), md: px('r-md'), lg: px('r-lg'), full: 999 },
  space: Object.fromEntries([...Array(12).keys()].map((i) => [i, Number(resolve('sp-' + i).light.replace(/px$/, '')) || 0])),
  control: { sm: 30, md: 36, lg: 44 },
  row: 52,
  avatarRadius: Number(resolve('av-radius').light),
  weight: { regular: '400', medium: '500', semibold: '600' },
};
const header = '// Generated by scripts/build-tokens.mjs from web/tokens.css. Do not edit by hand.\n';
const output = header + 'export const lightColors = ' + JSON.stringify(light, null, 2) + ' as const;\n\n' +
  'export const darkColors: { [K in keyof typeof lightColors]: string } = ' + JSON.stringify(dark, null, 2) + ';\n\n' +
  'export const typeScale = ' + JSON.stringify(typeScale, null, 2) + ' as const;\n\n' +
  'export const metrics = ' + JSON.stringify(metrics, null, 2) + ' as const;\n';
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== output) { console.error('tokens.generated.ts is stale: run npm run tokens'); process.exit(1); }
  console.log('tokens up to date:', Object.keys(light).length, 'colors');
} else {
  writeFileSync(target, output);
  console.log('wrote', target, '→', Object.keys(light).length, 'color tokens; accent', light.accent, '/', dark.accent);
}
